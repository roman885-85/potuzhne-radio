#ifndef spidma_h
#define spidma_h
/*  Вивід у дисплей через DMA.
    Штатний драйвер SPI ядра Arduino шле дані порціями по 64 байти й на кожну
    робить окреме рукостискання з очікуванням: на повний екран це 2400 порцій,
    і шина працює на дві третини своєї швидкості. Тут той самий периферійний
    блок SPI2 отримує дані напряму з пам'яті каналом GDMA, одним заходом.
    Налаштування шини (частота, режим, вивід CS і DC) лишаються за Adafruit:
    перед викликом має бути startWrite() і setAddrWindow().  */
#include <Arduino.h>

bool spidmaBegin();                               /* один раз; false — DMA недоступний */
/*  Буфер у внутрішній пам'яті, байти вже в порядку дисплея. false — не вийшло
    (DMA зламався чи вимкнений): тоді ці ж пікселі треба вивести звичайним шляхом.  */
bool spidmaWrite(const void* buf, size_t len);
bool spidmaOk();                                  /* DMA досі працює */
/*  Спільна смуга у внутрішній пам'яті для виводу через DMA. Внутрішньої пам'яті
    мало (від неї залежать TLS і Wi-Fi), а смуги потрібні списку станцій,
    спискам меню, кадру меню й заставці — усім у задачі дисплея й ніколи
    одночасно. Тож буфер один: не менше len байт, живе до перезавантаження.  */
void* spidmaScratch(size_t len);

#endif
