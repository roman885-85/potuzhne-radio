/*  ---------------------------------------------------------------------------
 *  Векторні інструкції ESP32-S3 (PIE) для найгарячіших циклів малювання.
 *
 *  Espressif ці інструкції не описує в документації на чип — поведінку кожної
 *  з'ясовано дослідом на самій платі (команда pietest), а не з припущень:
 *
 *    ee.vzip.8   qa,qb   перемішує байти: qa = a0,b0,a1,b1…a7,b7
 *                                          qb = a8,b8…a15,b15
 *    ee.vunzip.8 qa,qb   розбирає навпаки: qa = парні байти обох регістрів,
 *                                          qb = непарні
 *    ee.vldbc.16 q,addr  розмножує одне 16-бітне значення на весь регістр
 *    ee.vld/vst.128.ip   читання й запис 16 байтів з доважком до вказівника
 *
 *  128-бітні читання й записи вимагають вирівнювання на 16 байтів. Тому кожна
 *  функція сама обробляє невирівняний початок і остачу звичайним циклом, а
 *  якщо вирівняти не вдається — просто працює як раніше. Перевірка збігу з
 *  тим самим кодом без векторів — команда piecheck.
 *  ------------------------------------------------------------------------- */
#ifndef m2simd_h
#define m2simd_h
#include <Arduino.h>

namespace m2 {

/*  Заповнити n пікселів одним кольором.  */
inline void sFill(uint16_t* p, uint32_t n, uint16_t c){
  while(n && ((uintptr_t)p & 15)){ *p++ = c; n--; }      /* до межі 16 байтів */
  if(n >= 8){
    uint16_t __attribute__((aligned(16))) one[8] = { c, 0, 0, 0, 0, 0, 0, 0 };
    uint32_t blocks = n >> 3;
    n &= 7;
    __asm__ volatile("ee.vldbc.16 q0, %0\n" :: "r"(one) : "memory");
    while(blocks--) __asm__ volatile("ee.vst.128.ip q0, %0, 16\n" : "+r"(p) :: "memory");
  }
  while(n--) *p++ = c;
}

/*  Заповнити n пікселів візерунком, що повторюється кожні 8 пікселів.
    Потрібен градієнту: у рядку колір один, а розсіювання 4×4 дає лише
    чотири різні значення — вісім пікселів уже повторюються.  */
inline void sFillPat(uint16_t* p, uint32_t n, const uint16_t* pat8, uint8_t phase){
  /*  невирівняний початок — звичайним циклом, зсуваючи фазу візерунка  */
  while(n && ((uintptr_t)p & 15)){ *p++ = pat8[phase & 7]; phase++; n--; }
  if(n >= 8){
    uint16_t __attribute__((aligned(16))) blk[8];
    for(uint8_t i = 0; i < 8; i++) blk[i] = pat8[(phase + i) & 7];
    uint32_t blocks = n >> 3;
    n &= 7;
    __asm__ volatile("ee.vld.128.ip q0, %0, 0\n" :: "r"(blk) : "memory");
    while(blocks--) __asm__ volatile("ee.vst.128.ip q0, %0, 16\n" : "+r"(p) :: "memory");
  }
  while(n--){ *p++ = pat8[phase & 7]; phase++; }
}

/*  Переставити байти місцями в кожному пікселі (порядок дисплея).
    Робиться над усією смугою перед відправкою в екран.  */
inline void sSwap16(uint16_t* p, uint32_t n){
  while(n && ((uintptr_t)p & 15)){ uint16_t v = *p; *p++ = (uint16_t)((v >> 8) | (v << 8)); n--; }
  uint32_t blocks = n >> 4;                              /* по 16 пікселів = 32 байти */
  if(blocks){
    n &= 15;
    uint16_t* src = p;
    uint16_t* dst = p;
    while(blocks--){
      __asm__ volatile(
        "ee.vld.128.ip q0, %0, 16\n"
        "ee.vld.128.ip q1, %0, 16\n"
        "ee.vunzip.8   q0, q1\n"                         /* q0 = молодші байти, q1 = старші */
        "ee.vzip.8     q1, q0\n"                         /* q1 = старший+молодший по парах */
        "ee.vst.128.ip q1, %1, 16\n"
        "ee.vst.128.ip q0, %1, 16\n"
        : "+r"(src), "+r"(dst) :: "memory");
    }
    p = dst;
  }
  while(n--){ uint16_t v = *p; *p++ = (uint16_t)((v >> 8) | (v << 8)); }
}

}  // namespace m2
#endif
