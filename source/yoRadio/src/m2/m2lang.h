/*  Мова інтерфейсу.

    Переклад робиться в одному місці — там, де рядок перетворюється на літери
    для екрана (toCp1251 у m2gfx). Тому в коді сторінок нічого не змінилось:
    написи так і лишаються українськими, а таблиця нижче підміняє їх на
    англійські, коли в налаштуваннях вибрано English. Рядки, яких у таблиці
    немає (назви станцій, числа, адреси), проходять як є.  */
#ifndef m2lang_h
#define m2lang_h
#include <Arduino.h>

namespace m2 {

enum Lang : uint8_t { LANG_UK = 0, LANG_EN = 1, LANG_N };

/*  Поточна мова. Тримається тут, а не читається з налаштувань щоразу:
    переклад викликається на кожен напис у кожному кадрі.  */
extern uint8_t g_lang;
void langSet(uint8_t l);

/*  Переклад напису інтерфейсу. Повертає сам рядок, якщо мова українська
    або перекладу немає.  */
const char* tr(const char* uk);

}  // namespace m2
#endif
