/*  ---------------------------------------------------------------------------
 *  ES8311 — звуковой кодек платы ES3C28P.
 *
 *  Отличие от обычного I2S-ЦАПа: кодек не начнёт звучать, пока его регистры не
 *  настроены по I2C, и делители внутри него зависят от частоты дискретизации
 *  потока. Поэтому при каждой смене частоты кодек перенастраивается заново —
 *  это делает audio_samplerate_changed(), которую зовёт Audio::setSampleRate().
 *
 *  Работа идёт через Wire, а не через устаревший драйвер i2c из примеров
 *  производителя: в ядре ESP32 3.x Wire занимает шину новым драйвером, и два
 *  драйвера на одном порту не уживаются (на этой же шине висит тачскрин).
 *  ------------------------------------------------------------------------- */
#ifndef yoES8311_h
#define yoES8311_h

#include <Arduino.h>

bool es8311_begin(uint32_t sample_rate);        /* полная инициализация кодека  */
bool es8311_set_sample_rate(uint32_t rate);     /* перенастройка делителей      */
bool es8311_set_volume(uint8_t vol_0_100);      /* громкость ЦАПа, 75 = 0 dB    */
bool es8311_mute(bool mute);
bool es8311_suspend();       /* сон перед вимкненням радіо: аналогова частина знеструмлена */
bool es8311_ready();
void es8311_dump();          /* стан кодека для діагностики */

#endif
