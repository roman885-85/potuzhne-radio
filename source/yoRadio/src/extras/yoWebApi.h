/*  ---------------------------------------------------------------------------
 *  Веб-API ПОТУЖНОГО РАДІО для нової веб-сторінки.
 *
 *  Сторінка yoRadio говорила з платою лише через websocket і знала тільки
 *  те, що було в yoRadio. Усе дописане (сон, будильник, екран, обране,
 *  проповіді, запис, батарея, розробник, логотипи) віддаємо тут, у JSON:
 *
 *    GET  /api/state      усе, що змінюється, — сторінка питає раз на 2 с
 *    POST /api/set        k=v[&k=v...] — команди; виконує головний цикл
 *    GET  /api/sermons    список проповідей із сайту
 *    GET  /api/records    записи на картці; /api/rec?f=... — завантажити
 *    GET  /api/wifi       збережені мережі й результат пошуку
 *    POST /api/wifi/join  ssid, pass — підключитись (перезавантаження)
 *    GET  /api/stations   сирий список станцій із SPIFFS (і в режимі картки)
 *    POST /api/stations   новий список цілком — від редактора станцій
 *    GET  /api/logos      які логотипи вже є; самі файли — /logo/<crc>.565
 *    POST /api/logo       свій логотип станції (45x45 RGB565 від сторінки)
 *
 *  Обробники веб-сервера працюють у задачі async_tcp, а плеєр, картка й
 *  налаштування належать головному циклу. Тому команди лише кладемо в
 *  чергу, а виконує їх yoWebApiLoop() — там само, де звучить декодер.
 *  ------------------------------------------------------------------------- */
#ifndef yoWebApi_h
#define yoWebApi_h

class AsyncWebServer;
void yoWebApiBegin(AsyncWebServer& s);   /* до serveStatic("/") */
void yoWebApiLoop();                     /* з головного циклу */

#endif
