/*  ---------------------------------------------------------------------------
 *  Справжній спектр звуку для головного екрана.
 *
 *  Задача звуку кладе кожен відлік (моно, ще до еквалайзера й гучності —
 *  спектр не залежить від того, наскільки гучно грає динамік) у кільцевий
 *  буфер: одна інструкція на відлік. Задача дисплея раз на кілька десятків
 *  мілісекунд бере останні 2048 відліків, множить на вікно Ганна, робить
 *  швидке перетворення Фур'є й складає енергію в смуги з логарифмічним
 *  кроком (50 Гц … 16 кГц). Звуку немає — смуги нульові, нічого не «дихає».
 *  ------------------------------------------------------------------------- */
#ifndef yoSpectrum_h
#define yoSpectrum_h
#include <Arduino.h>

class YoSpectrum {
  public:
    static const uint16_t N = 2048;      /* 21,5 Гц на відлік при 44,1 кГц — низи розрізняються */
    /*  задача звуку: відлік до обробки (буфер — у PSRAM, з'являється з першим кадром екрана)  */
    inline void push(int16_t l, int16_t r){
      if(!_buf) return;
      _buf[_w] = (int16_t)(((int32_t)l + r) >> 1);
      _w = (_w + 1) & (N - 1);
      if(!(_w & 0xFF)) _lastMs = millis();
    }
    /*  задача дисплея: рівні смуг 0..1 (з м'яким спадом). false — звуку немає  */
    bool bands(float* out, uint8_t n, uint32_t sampleRate);
    /*  підбір без перезбирання (команда specset): шкала дБ, запас над піком дБ, спад верху дБ/с, усереднення  */
    float range = 30.0f, head = 6.0f, decay = 5.0f, avgK = 0.7f;
  private:
    int16_t* volatile _buf = nullptr;
    volatile uint16_t _w = 0;
    volatile uint32_t _lastMs = 0;
    float*  _re = nullptr, *_im = nullptr, *_win = nullptr;
    float   _avg[64] = { 0 };            /* усереднення по часу: одне вікно Фур'є саме по собі скаче */
    float   _smooth[64] = { 0 };
    uint32_t _lastT = 0;
    float   _ref = -30.0f;               /* верх шкали, дБ — іде за гучністю */
    bool    _refOk = false;
};

extern YoSpectrum yoSpec;

#endif
